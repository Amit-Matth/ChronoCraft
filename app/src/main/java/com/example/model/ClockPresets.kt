  fun applyThemePack(config: WidgetConfig, pack: ClockThemePack): WidgetConfig {
    val cardStyle = when (pack.fillMode) {
      BackgroundFillMode.NONE -> CardStyle.TRANSPARENT
      BackgroundFillMode.GLASS -> CardStyle.FROSTED
      else -> CardStyle.SOLID
    }
    return config.copy(
      themePackId = pack.id,
      fontId = pack.fontId,
      backgroundFillMode = pack.fillMode,
      cardStyle = cardStyle,
      backdropId = if (pack.fillMode == BackgroundFillMode.ARTWORK) config.backdropId else WidgetBackdropId.NONE,
      backgroundColor = pack.backgroundColor,
      backgroundSecondaryColor = pack.backgroundSecondaryColor,
      accentColor = pack.accentColor,
      foregroundColor = pack.foregroundColor,
      secondaryTextColor = pack.secondaryTextColor,
      borderColor = pack.borderColor,
      backgroundAlpha = pack.backgroundAlpha,
      showBorder = pack.showBorder,
      hourColor = null,
      minuteColor = null,
      secondsColor = null,
      animationStyle = pack.animationStyle,
      glowIntensity = pack.glowIntensity,
      animationsEnabled = pack.animationStyle != ClockAnimationStyle.NONE,
    )
  }
